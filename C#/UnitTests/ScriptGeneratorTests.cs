    [TestFixture]
    class ScriptGeneratorTests
    {
        private static readonly DateTime Stamp = new DateTime(2026, 1, 2, 3, 4, 0);

        private static AppConfig SampleConfig()
        {
            var config = AppConfig.CreateDefault();
            config.Devices.Add(new DeviceRef { Key = "kb1", Name = "Keyboard", Handle = @"HID\VID_046D&PID_C31C", Vid = 0x46D, Pid = 0xC31C });
            config.Devices.Add(new DeviceRef { Key = "m1", Name = "Mouse", IsMouse = true, Handle = @"HID\VID_1234&PID_0001" });
            config.Devices.Add(new DeviceRef { Key = "unused", Name = "Unused" });
            config.DefaultProfile.Mappings.Add(new Mapping { DeviceKey = "kb1", Input = InputKind.Key, Code = 0x3A, Action = ActionType.Key, TargetCode = 0x01 });
            config.DefaultProfile.Mappings.Add(new Mapping { DeviceKey = "m1", Input = InputKind.Mouse, Code = MouseCodes.XButton1, Action = ActionType.Send, Value = "^c" });
            config.Profiles.Insert(0, new Profile
            {
                Name = "Notepad",
                MatchType = MatchType.Exe,
                MatchValue = "notepad.exe",
                Mappings = { new Mapping { DeviceKey = "kb1", Input = InputKind.Key, Code = 0x3B, Action = ActionType.Text, Value = "hello" } }
            });
            return config;
        }

        [Test]
        public void GeneratesExpectedScript()
        {
            var script = ScriptGenerator.Generate(SampleConfig(), @"C:\AHI\AHK v2\Lib\AHIRuntime.ahk", @"C:\AHI\Configurator\AHIConfigurator.exe", Stamp);
            var expected = string.Join(Environment.NewLine,
                "; Generated by the AutoHotInterception Configurator on 2026-01-02 03:04.",
                "; Do not edit: changes are overwritten the next time you click Apply. Use Export in the Configurator to get an editable copy.",
                "#Requires AutoHotkey v2.0",
                "#SingleInstance Force",
                "SetTitleMatchMode(2)",
                "#Include \"C:\\AHI\\AHK v2\\Lib\\AHIRuntime.ahk\"",
                "",
                "AHIRuntime.Start(Map(",
                "\t\"configurator\", \"C:\\AHI\\Configurator\\AHIConfigurator.exe\",",
                "\t\"devices\", [",
                "\t\tMap(\"key\", \"kb1\", \"name\", \"Keyboard\", \"isMouse\", 0, \"handle\", \"HID\\VID_046D&PID_C31C\", \"vid\", 0x46D, \"pid\", 0xC31C, \"instance\", 1),",
                "\t\tMap(\"key\", \"m1\", \"name\", \"Mouse\", \"isMouse\", 1, \"handle\", \"HID\\VID_1234&PID_0001\", \"vid\", 0x0, \"pid\", 0x0, \"instance\", 1)",
                "\t],",
                "\t\"profiles\", [",
                "\t\tMap(\"name\", \"Notepad\", \"match\", \"ahk_exe notepad.exe\", \"mappings\", [",
                "\t\t\tMap(\"dev\", \"kb1\", \"input\", \"key\", \"code\", 0x3B, \"action\", \"text\", \"value\", \"hello\", \"args\", \"\")",
                "\t\t]),",
                "\t\tMap(\"name\", \"Default (all applications)\", \"match\", \"\", \"mappings\", [",
                "\t\t\tMap(\"dev\", \"kb1\", \"input\", \"key\", \"code\", 0x3A, \"action\", \"key\", \"value\", 0x1, \"args\", \"\"),",
                "\t\t\tMap(\"dev\", \"m1\", \"input\", \"mouse\", \"code\", 3, \"action\", \"send\", \"value\", \"^c\", \"args\", \"\")",
                "\t\t])",
                "\t]",
                "))",
                "");
            Assert.That(script, Is.EqualTo(expected));
        }

        [Test]
        public void DefaultProfileIsAlwaysLast()
        {
            var config = SampleConfig();
            // Simulate a hand-edited config with the default profile first
            var def = config.DefaultProfile;
            config.Profiles.Remove(def);
            config.Profiles.Insert(0, def);
            var script = ScriptGenerator.Generate(config, "r.ahk", "", Stamp);
            Assert.That(script.IndexOf("\"Notepad\"", StringComparison.Ordinal), Is.LessThan(script.IndexOf("\"Default (all applications)\"", StringComparison.Ordinal)));
        }

        [Test]
        public void SkipsMappingsOfUnknownDevices()
        {
            var config = SampleConfig();
            config.DefaultProfile.Mappings.Add(new Mapping { DeviceKey = "ghost", Code = 0x10, Action = ActionType.Block });
            var script = ScriptGenerator.Generate(config, "r.ahk", "", Stamp);
            Assert.That(script, Does.Not.Contain("ghost"));
            Assert.That(script, Does.Not.Contain("\"unused\""), "devices without mappings are left out");
        }

        [Test]
        public void EmptyProfileRendersEmptyArray()
        {
            var script = ScriptGenerator.Generate(AppConfig.CreateDefault(), "r.ahk", "", Stamp);
            Assert.That(script, Does.Contain("\"devices\", [\r\n\t],"));
            Assert.That(script, Does.Contain("\"mappings\", [])"));
        }

        [TestCase("plain", "\"plain\"")]
        [TestCase("say \"hi\"", "\"say `\"hi`\"\"")]
        [TestCase("a`b", "\"a``b\"")]
        [TestCase("x ;not a comment", "\"x `;not a comment\"")]
        [TestCase("line1\r\nline2\tend", "\"line1`r`nline2`tend\"")]
        [TestCase("{Enter}%A_Now%", "\"{Enter}%A_Now%\"")]
        public void QuotesAhkStrings(string input, string expected)
        {
            Assert.That(ScriptGenerator.Quote(input), Is.EqualTo(expected));
        }

        // ------------------------------------------------------------------ With a real AutoHotkey

        private static string RequireAutoHotkey()
        {
            var ahk = ScriptRunner.FindAutoHotkey(null);
            if (ahk == null) Assert.Ignore("AutoHotkey v2 is not installed");
            return ahk;
        }

        private static string RepoRuntime()
        {
            var dir = TestContext.CurrentContext.TestDirectory;
            while (dir != null)
            {
                var candidate = Path.Combine(dir, AppPaths.RuntimeRelativePath);
                if (File.Exists(candidate)) return candidate;
                dir = Path.GetDirectoryName(dir);
            }
            Assert.Fail("AHIRuntime.ahk not found above " + TestContext.CurrentContext.TestDirectory);
            return null;
        }

        [Test, Category("AutoHotkey")]
        public void GeneratedScriptLoadsInAutoHotkey()
        {
            var ahk = RequireAutoHotkey();
            var script = Path.Combine(Path.GetTempPath(), "AHI-GeneratorTest-" + Guid.NewGuid().ToString("N") + ".ahk");
            try
            {
                var config = SampleConfig();
                config.DefaultProfile.Mappings.Add(new Mapping { DeviceKey = "kb1", Input = InputKind.Key, Code = 0x3C, Action = ActionType.Run, Value = "\"C:\\Program Files\\x.exe\" /a", Args = "C:\\" });
                File.WriteAllText(script, ScriptGenerator.Generate(config, RepoRuntime(), "", Stamp), new UTF8Encoding(true));
                Assert.That(ScriptRunner.Validate(ahk, script), Is.Null);
            }
            finally
            {
                File.Delete(script);
            }
        }

        /// <summary>
        /// Runs the generated script against a stub runtime that prints the values it receives,
        /// proving that awkward strings survive quoting unchanged.
        /// </summary>
        [Test, Category("AutoHotkey")]
        public void StringsRoundTripThroughAutoHotkey()
        {
            var ahk = RequireAutoHotkey();
            var dir = Path.Combine(Path.GetTempPath(), "AHI-GeneratorTest-" + Guid.NewGuid().ToString("N"));
            Directory.CreateDirectory(dir);
            try
            {
                var tricky = new[] { "say \"hi\" ; ok", "back`tick", "two\r\nlines\tand tab", "{Enter}%A_Now% ünïcödé €" };
                var config = SampleConfig();
                config.DefaultProfile.Mappings.Clear();
                foreach (var t in tricky)
                    config.DefaultProfile.Mappings.Add(new Mapping { DeviceKey = "kb1", Code = 0x10, Action = ActionType.Text, Value = t });

                var stub = Path.Combine(dir, "StubRuntime.ahk");
                File.WriteAllText(stub,
                    "class AHIRuntime {\n" +
                    "\tstatic Start(config) {\n" +
                    "\t\tout := \"\"\n" +
                    "\t\tfor m in config[\"profiles\"][-1][\"mappings\"]\n" +
                    "\t\t\tout .= m[\"value\"] \"|END|\"\n" +
                    "\t\tFileAppend(out, A_ScriptDir \"\\out.txt\", \"UTF-8-RAW\")\n" +
                    "\t\tExitApp\n" +
                    "\t}\n" +
                    "}\n", new UTF8Encoding(true));
                var script = Path.Combine(dir, "test.ahk");
                File.WriteAllText(script, ScriptGenerator.Generate(config, stub, "", Stamp), new UTF8Encoding(true));

                using (var p = Process.Start(new ProcessStartInfo(ahk, $"/ErrorStdOut \"{script}\"") { UseShellExecute = false, CreateNoWindow = true }))
                {
                    Assert.That(p.WaitForExit(15000), Is.True, "AutoHotkey did not exit");
                }
                var values = File.ReadAllText(Path.Combine(dir, "out.txt"), Encoding.UTF8)
                    .Split(new[] { "|END|" }, StringSplitOptions.None).Take(tricky.Length);
                Assert.That(values, Is.EqualTo(tricky));
            }
            finally
            {
                Directory.Delete(dir, true);
            }
        }
    }
