using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using AHIConfigurator.Models;

namespace AHIConfigurator.Services
{
    /// <summary>
    /// Turns an <see cref="AppConfig"/> into an AHK v2 script. The script only contains data;
    /// all behaviour is in AHK v2\Lib\AHIRuntime.ahk (see the comment at the top of that file for the format).
    /// </summary>
    public static class ScriptGenerator
    {
        public static string Generate(AppConfig config, string runtimePath, string configuratorPath, DateTime generatedAt)
        {
            var usedDevices = new HashSet<string>(config.Profiles.SelectMany(p => p.Mappings).Select(m => m.DeviceKey));
            var devices = config.Devices.Where(d => usedDevices.Contains(d.Key)).ToList();
            var deviceKeys = new HashSet<string>(devices.Select(d => d.Key));
            // App profiles first (in the user's order), the default profile last so it acts as the fallback
            var profiles = config.Profiles.Where(p => !p.IsDefault).Concat(config.Profiles.Where(p => p.IsDefault));

            var sb = new StringBuilder();
            sb.AppendLine("; Generated by the AutoHotInterception Configurator on " + generatedAt.ToString("yyyy-MM-dd HH:mm", CultureInfo.InvariantCulture) + ".");
            sb.AppendLine("; Do not edit: changes are overwritten the next time you click Apply. Use Export in the Configurator to get an editable copy.");
            sb.AppendLine("#Requires AutoHotkey v2.0");
            sb.AppendLine("#SingleInstance Force");
            sb.AppendLine("SetTitleMatchMode(2)");
            sb.AppendLine("#Include " + Quote(runtimePath));
            sb.AppendLine();
            sb.AppendLine("AHIRuntime.Start(Map(");
            sb.AppendLine("\t\"configurator\", " + Quote(configuratorPath ?? "") + ",");

            sb.AppendLine("\t\"devices\", [");
            AppendItems(sb, devices.Select(d =>
                $"\t\tMap(\"key\", {Quote(d.Key)}, \"name\", {Quote(d.Name ?? "")}, \"isMouse\", {(d.IsMouse ? 1 : 0)}, " +
                $"\"handle\", {Quote(d.Handle ?? "")}, \"vid\", {Hex(d.Vid)}, \"pid\", {Hex(d.Pid)}, \"instance\", {d.Instance})"));
            sb.AppendLine("\t],");

            sb.AppendLine("\t\"profiles\", [");
            AppendItems(sb, profiles.Select(p =>
            {
                var mappings = p.Mappings.Where(m => deviceKeys.Contains(m.DeviceKey)).ToList();
                var head = $"\t\tMap(\"name\", {Quote(p.Name ?? "")}, \"match\", {Quote(p.ToWinTitle())}, \"mappings\", [";
                if (mappings.Count == 0) return head + "])";
                var inner = new StringBuilder();
                inner.AppendLine(head);
                AppendItems(inner, mappings.Select(m => "\t\t\t" + RenderMapping(m)));
                inner.Append("\t\t])");
                return inner.ToString();
            }));
            sb.AppendLine("\t]");
            sb.AppendLine("))");
            return sb.ToString();
        }

        public static string RenderMapping(Mapping m)
        {
            string action, value;
            switch (m.Action)
            {
                case ActionType.Key: action = "key"; value = Hex(m.TargetCode); break;
                case ActionType.Mouse: action = "mouse"; value = m.TargetCode.ToString(CultureInfo.InvariantCulture); break;
                case ActionType.Block: action = "block"; value = "\"\""; break;
                case ActionType.PassThrough: action = "passthru"; value = "\"\""; break;
                case ActionType.Text: action = "text"; value = Quote(m.Value ?? ""); break;
                case ActionType.Send: action = "send"; value = Quote(m.Value ?? ""); break;
                case ActionType.Run: action = "run"; value = Quote(m.Value ?? ""); break;
                default: throw new ArgumentOutOfRangeException(nameof(m), m.Action, "Unknown action");
            }
            var input = m.Input == InputKind.Mouse ? "mouse" : "key";
            var code = m.Input == InputKind.Mouse ? m.Code.ToString(CultureInfo.InvariantCulture) : Hex(m.Code);
            return $"Map(\"dev\", {Quote(m.DeviceKey)}, \"input\", \"{input}\", \"code\", {code}, " +
                   $"\"action\", \"{action}\", \"value\", {value}, \"args\", {Quote(m.Args ?? "")})";
        }

        /// <summary>
        /// AHK v2 double-quoted string literal. Backtick is the escape character; ";" is escaped too
        /// so " ;" can never be read as a comment.
        /// </summary>
        public static string Quote(string s)
        {
            var sb = new StringBuilder("\"");
            foreach (var c in s)
            {
                switch (c)
                {
                    case '`': sb.Append("``"); break;
                    case '"': sb.Append("`\""); break;
                    case ';': sb.Append("`;"); break;
                    case '\r': sb.Append("`r"); break;
                    case '\n': sb.Append("`n"); break;
                    case '\t': sb.Append("`t"); break;
                    default: sb.Append(c); break;
                }
            }
            return sb.Append('"').ToString();
        }

        private static string Hex(int value) => "0x" + value.ToString("X", CultureInfo.InvariantCulture);

        // AHK does not allow a trailing comma in array literals, so join with ",\n"
        private static void AppendItems(StringBuilder sb, IEnumerable<string> items)
        {
            var list = items.ToList();
            for (var i = 0; i < list.Count; i++)
                sb.AppendLine(list[i] + (i < list.Count - 1 ? "," : ""));
        }
    }
}
